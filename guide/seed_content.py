("College rooms, family housing and private renting", "living", """
The room is not just where you sleep: it controls cooking, family life,
cost and recovery.

## College accommodation

Often cheaper and simpler than private rent — but frequently designed
around a single student who leaves in vacations. Contracts commonly ran
27–39 weeks in recent years; **your actual licence is the authority**. Ask,
in writing: can you stay through Christmas and Easter (and at what charge)?
Is residence allowed for work/family reasons or only academic ones? Is
storage available? Do conferences displace students? Can disability,
parenting or caring need be considered before the general room ballot?

## Couples and family housing

Stock is limited and concentrated. "Family accommodation available" does
not mean guaranteed, affordable, near your faculty, or suitable for the
school run. Ask for: number of units, allocation priority, waiting-list
position, lease length, bills, play space, accessibility — and what happens
if the relationship changes. A partner is not automatically a college
member; children's access to gardens, libraries, halls and bars is
college-specific. Get the guest and safeguarding rules in writing.

## Private renting

View in person (or reliable live video). Confirm deposit protection, lawful
fees, included bills, guarantor requirements. Read break clauses and
**joint-and-several liability** — another tenant's non-payment can become
your problem. Check licensing and repairs routes; keep the advert,
inventory and meter readings. **Council Tax**: an all-full-time-student
household is generally exempt; one countable non-student changes that —
calculate before signing.

## Living out, commuting and "keeping term"

Living out preserves adult autonomy and stable schooling at the cost of
travel time and spontaneity. Test the route at 08:30, after 18:00 and in
bad weather. Crucially, undergraduates must satisfy the University's
residence ("keeping term") requirement, certified through the college —
some handbooks express it as roughly 59/59/52 nights across the three
terms. A nearby-village commute can be workable; **a London commute is not
an informal loophole**. Parents/carers: agree in advance how custody
patterns and emergency travel are recorded — advance approval, not hoping
nobody notices.
"""),

