("Partners, parenting and caring alongside the degree", "family", """
Cambridge can accommodate adult life, but it does not automatically
*organise* it.

## Partners

A partner does not become a University member through your admission —
access to dining, libraries, gyms and events is governed separately, and
varies. Agree household terms before term starts: protected study blocks,
pickups, illness contingencies, money limits, and what happens during
revision. A student timetable *looks* flexible because reading isn't on a
calendar; it is still work — and the partner must not become an invisible
unpaid support service. (MSS runs a [Partners Club](/events/tags/partners-club/)
for exactly this reason.)

## Parents and carers

- Two backup plans for collection, always.
- Give school/nursery the right emergency contacts; explain which college
  gates cars can't reach.
- Ask supervisors for predictable scheduling where possible — and accept
  that not every practical can move.
- Build belonging on daytime events and parent networks, not 10pm
  availability.
- Plan vacation study openly: "no lectures" is not "no work".
- For adult caring, set up respite, medication and emergency handover —
  the University cannot replace statutory care services.

## Pregnancy and new parents

The University publishes pregnancy/maternity study routes, but the real
arrangement needs course, college, health, funding and (sometimes) visa
coordination. Contact your Tutor early; request risk assessments for labs
or placements; get intermission or adjusted-study dates **in writing**.
Intermission affects housing, student finance, benefits and visas — decide
with a whole-life map, not just an academic calendar.

## The family emergency plan (make it now)

Child ill on essay day → who receives the deadline request, which adult
covers. Nursery closes → one backup carer identified. Partner hospitalised
→ list of dependants, medication, school contacts, cash access. Relative
crisis away from Cambridge → travel threshold and an emergency fund.
Relationship breakdown → know your tenancy status, separate finances, safe
contacts and the college emergency-housing route.

Your responsibilities are part of planning — **not an embarrassing exception
to disclose only after failure**.
"""),

("Welfare, health and disability: making support work", "family", """
Know the difference between support, treatment, emergency response and
formal procedure — then pair the right service with a concrete request.

## Four levels of urgency

1. **Immediate emergency** — 999/112, then the Porters' Lodge if you need
   college access or an ambulance directed to the right gate. Email is not
   an emergency response.
2. **Urgent but not 999** — NHS 111, your GP's urgent route, or a crisis
   team. **Samaritans: 116 123**, any hour. The counselling service is not
   an emergency service.
3. **Next working day** — email your Tutor with a clear request:
   appointment, deadline action, financial help, referral. Copy the DoS
   only when academic arrangements are affected.
4. **Long-term condition** — ADRC + college early; ask who implements each
   adjustment and what separate exam application applies. Review it before,
   not during, exam term.

## Disability and neurodivergence

Reasonable adjustments are not favours, and they don't require performed
gratitude — they require **specificity and implementation**. A Student
Support Document recommends; college, faculty and the exam system each
implement. Ask for reading lists in time to convert formats; test assistive
tech before high-stakes weeks; clarify whether extensions are automatic or
per-request; keep a dated log when agreed measures go missing — report the
*effect* ("I lost three hours obtaining a readable copy"), not just the
breach.

## Mental health

Don't wait for diagnostic certainty. Tell someone what's happening
*functionally* — sleep, eating, attendance, concentration, safety. The
Tutor handles college consequences; the GP handles clinical need; the DoS
adjusts academic planning. For bereavement, addiction, eating difficulty or
abuse, specialist routes beat a generic college conversation — and support
should not be conditional on making a formal complaint.

## When illness hits the work

Get safe → tell Tutor and DoS that work is affected (no full medical
narrative needed to every supervisor) → ask exactly what changes → keep
evidence and a timeline → review the next two weeks so the backlog doesn't
reproduce the crisis.
"""),

