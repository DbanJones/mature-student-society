("How Cambridge actually works", "study", """
Cambridge is a **federation**, and learning its map before a crisis is the
single most useful piece of preparation.

## Three overlapping institutions

- The **University** sets degrees and examinations, and runs central
  services: libraries and IT, the disability centre (ADRC), counselling,
  careers, complaints procedures.
- Your **Faculty or Department** runs the subject: lectures, labs, seminars,
  handbooks, paper content, placements, coursework and exam guidance.
- Your **College** is your home: admission, accommodation, meals,
  supervisions, Director of Studies, Tutor, local welfare, grants,
  community and ceremonies.

A timetable problem, a rent problem and a health problem are therefore
**three different conversations**. The question that unlocks most tangles:
*"Is this a University rule, a Faculty rule, or my college's practice?"*

## The people (learn this by heart)

- **Supervisor** — teaches a particular paper in a small group; detailed
  academic feedback on that work.
- **Director of Studies (DoS)** — your college's academic coordinator:
  arranges supervisors, monitors reports, advises on paper choices, and is
  the right door when difficulty is persistent or structural.
- **Tutor** — a *pastoral* college role, usually not your subject: illness,
  bereavement, money, family, welfare, intermission.
- **Senior Tutor** — escalation point, not first contact.
- **Porters' Lodge** — keys, safety, visitors, post, practical incidents;
  often operates beyond office hours. ("Plodge", colloquially.)
- **Faculty administrator** — the operational expert: timetables, forms,
  submissions, the current written rule.
- **Cambridge SU Student Advice** — free, confidential, impartial, and
  independent of your college.

Say *"my Tutor is pastoral, my DoS coordinates my academics, my supervisor
teaches this paper"* until it's instinct — then use the
[who-to-contact map](/faq/who-to-contact/) when something breaks.

## Confidentiality: ask, don't guess

Tutors, nurses, counsellors, porters and reps have different duties. Before
disclosing something sensitive, ask what will be recorded, who can see it,
and what would require them to share it. In immediate-risk situations,
safety overrides normal confidentiality.
"""),

("Supervisions: what they are and how to use them", "study", """
A supervision is a small-group academic meeting — usually about an hour,
arranged through your college. It is **not** a private lesson, a counselling
session, or an oral exam where every answer must be right. Its value lies in
**exposing your reasoning**.

## Before, during, after

- **Before**: read the question early; identify the task verb; choose what
  *not* to read; submit on time; write three questions you genuinely need
  answered.
- **During**: stay in the conversation. Say *"I do not see why that
  follows"* rather than nodding. Take enough notes to capture corrections.
- **After**: ten minutes to record the main correction, one technique to
  repeat, one issue for the DoS, one concrete action before the next piece.

## The workload behind it

Cambridge describes undergraduate study as **at least ~35 hours a week**,
with wide course variation — lab sciences have fixed practicals and problem
sheets; humanities have fewer contact hours but relentless reading and
essays; clinical, education and language courses add placements. Full Term
is eight weeks, but the year is not 24 weeks: vacations carry reading,
revision and projects.

## When it goes badly

Distinguish tough intellectual challenge from contempt, inconsistency or
inaccessible practice. Ordinary critical feedback stings — returners often
read it as proof they've "lost it". They haven't. Ask the supervisor for the
**two highest-priority changes** and apply them to the next piece; raise a
repeating pattern with your DoS.

The classic mature-student mistake: concealing confusion until you can
present a fully solved problem. The supervision is *where reasoning is meant
to be tested*.
"""),

